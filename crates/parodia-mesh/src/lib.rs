//! parodia-mesh — превращает блоки чанка в «квады» (прямоугольники граней) для видеокарты.
//!
//! Видеокарта не умеет рисовать «блок» — только треугольники. Поэтому для каждого чанка
//! мы заранее строим список видимых граней, а соседние одинаковые грани сливаем в один большой
//! прямоугольник (greedy meshing): ровный пол 32×32 из одного блока — это 1 квад, а не 1024.
//!
//! Алгоритм — binary greedy meshing (идея из открытого проекта cgerikj/binary-greedy-meshing,
//! код свой): столбец из 34 ячеек хранится как биты одного числа u64, и видимые грани находятся
//! сразу для всего столбца двумя побитовыми операциями.
//!
//! Формат квада — 2 числа u32 (8 байт на прямоугольник любого размера):
//! - слово 0: x(5 бит) | y(5) | z(5) | ширина−1 (5) | высота−1 (5) | грань (3)
//! - слово 1: номер блока (16 бит); старшие 16 бит зарезервированы (освещение, AO — этап 7).
//!
//! Файлы: `binary.rs` — сам алгоритм.

mod binary;

pub use binary::{Mesher, Neighborhood};

/// Сторона грани. Порядок совпадает с шейдером `terrain.vert`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u32)]
pub enum Face {
    PosX = 0,
    NegX = 1,
    PosY = 2,
    NegY = 3,
    PosZ = 4,
    NegZ = 5,
}

impl Face {
    pub const ALL: [Face; 6] = [
        Face::PosX,
        Face::NegX,
        Face::PosY,
        Face::NegY,
        Face::PosZ,
        Face::NegZ,
    ];
}

/// Слов u32 на один квад.
pub const QUAD_WORDS: usize = 2;

/// Упаковывает квад. `x, y, z` — угол клетки внутри чанка (0..31), `w, h` — размеры (1..32).
/// Оси ширины и высоты: для граней X — (y, z), для граней Y — (x, z), для граней Z — (x, y).
#[inline]
pub fn pack_quad(x: u32, y: u32, z: u32, w: u32, h: u32, face: Face, block: u16) -> [u32; 2] {
    debug_assert!(x < 32 && y < 32 && z < 32 && (1..=32).contains(&w) && (1..=32).contains(&h));
    [
        x | y << 5 | z << 10 | (w - 1) << 15 | (h - 1) << 20 | (face as u32) << 25,
        block as u32,
    ]
}

/// Обратное к `pack_quad` (для тестов и отладки): (x, y, z, w, h, face, block).
pub fn unpack_quad(words: [u32; 2]) -> (u32, u32, u32, u32, u32, u32, u16) {
    let a = words[0];
    (
        a & 31,
        (a >> 5) & 31,
        (a >> 10) & 31,
        ((a >> 15) & 31) + 1,
        ((a >> 20) & 31) + 1,
        (a >> 25) & 7,
        (words[1] & 0xFFFF) as u16,
    )
}
